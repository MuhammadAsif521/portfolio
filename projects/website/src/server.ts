import {
  AngularNodeAppEngine,
  createNodeRequestHandler,
  isMainModule,
  writeResponseToNodeResponse,
} from '@angular/ssr/node';
import express from 'express';
import { join } from 'node:path';
import { networkInterfaces } from 'node:os';

const browserDistFolder = join(import.meta.dirname, '../browser');

const app = express();

const isDev = process.env['NODE_ENV'] !== 'production';

function getDevHosts(): string[] {
  const hosts = [
    'localhost',
    '127.0.0.1',
    '0.0.0.0',
  ];
  try {
    const nets = networkInterfaces();
    for (const ifaces of Object.values(nets)) {
      if (!ifaces) continue;
      for (const iface of ifaces) {
        if (iface.family === 'IPv4' && !iface.internal) {
          hosts.push(iface.address);
        }
      }
    }
  } catch { }
  return hosts;
}

const angularApp = new AngularNodeAppEngine({
  allowedHosts: isDev
    ? [
      ...getDevHosts(),
      '*.devtunnels.ms'
    ]
    : // Production hostnames this SSR server answers for (comma-separated), e.g. "asifdev.com,www.asifdev.com".
      (process.env['ALLOWED_HOSTS'] ?? 'asifdev.com,www.asifdev.com')
        .split(',')
        .map((host) => host.trim())
        .filter(Boolean),
  trustProxyHeaders: true,
});


// ── Static Files ───────────────────────────────────────────────
app.use(
  express.static(browserDistFolder, {
    maxAge: '1y',
    index: false,
    redirect: false,
  }),
);

// ── Crawler files ──────────────────────────────────────────────
// sitemap.xml, robots.txt, llms.txt, llms-full.txt and the IndexNow key file are generated by
// portfolio-node at its site root; this passthrough serves them on the website's own host (Vercel sends
// every non-static path to this server).
const apiOrigin = new URL(process.env['API_INTERNAL_URL'] ?? 'http://localhost:3000/api/v1').origin;
const crawlerFiles = ['/sitemap.xml', '/robots.txt', '/llms.txt', '/llms-full.txt'];
/** Old or alternative llms.txt locations: one canonical URL, so they redirect permanently. */
const llmsAliases = ['/llm.txt', '/.well-known/llms.txt', '/.well-known/llm.txt'];
/** IndexNow key file (/<key>.txt); portfolio-node answers 404 unless it is the configured key. */
const indexNowKeyFile = /^\/[A-Za-z0-9-]{8,128}\.txt$/;

app.get(llmsAliases, (_req, res) => {
  res.setHeader('Cache-Control', 'public, max-age=86400');
  res.redirect(301, '/llms.txt');
});

/**
 * The API runs on a free tier that sleeps: a cold start can outlast the serverless timeout, and Search
 * Console then reports "Sitemap could not be read". So (1) Vercel's CDN keeps a good copy for an hour and
 * serves it stale while revalidating / when the API errors, (2) this instance keeps its last good copy,
 * and (3) with nothing to fall back on the answer is a 503 + Retry-After (crawlers retry), never HTML.
 */
const CRAWLER_CDN_CACHE = 'max-age=3600, stale-while-revalidate=604800, stale-if-error=604800';
const UPSTREAM_TIMEOUT_MS = 25_000;
const lastGood = new Map<string, { status: number; headers: [string, string][]; body: Buffer }>();

app.get([...crawlerFiles, indexNowKeyFile], async (req, res) => {
  const forwarded = ['content-type', 'cache-control', 'etag', 'location', 'x-robots-tag'];
  try {
    // Never follow upstream redirects: the visitor (or crawler) must see them itself.
    const upstream = await fetch(`${apiOrigin}${req.path}`, {
      redirect: 'manual',
      signal: AbortSignal.timeout(UPSTREAM_TIMEOUT_MS),
    });
    if (upstream.status >= 500) throw new Error(`upstream ${upstream.status}`);
    const headers = forwarded
      .map((name) => [name, upstream.headers.get(name)] as const)
      .filter((pair): pair is [string, string] => pair[1] !== null);
    const body = Buffer.from(await upstream.arrayBuffer());
    if (upstream.status === 200) lastGood.set(req.path, { status: 200, headers, body });

    res.status(upstream.status);
    for (const [name, value] of headers) res.setHeader(name, value);
    if (upstream.status === 200) res.setHeader('Vercel-CDN-Cache-Control', CRAWLER_CDN_CACHE);
    res.send(body);
  } catch (err) {
    const cached = lastGood.get(req.path);
    if (cached) {
      res.status(cached.status);
      for (const [name, value] of cached.headers) res.setHeader(name, value);
      res.setHeader('Vercel-CDN-Cache-Control', 'max-age=60'); // retry the API soon
      res.send(cached.body);
      return;
    }
    console.warn(`[crawler-files] ${req.path}: API unavailable (${err instanceof Error ? err.message : 'error'})`);
    res
      .status(503)
      .set({ 'Retry-After': '120', 'Cache-Control': 'no-store', 'Content-Type': 'text/plain; charset=utf-8' })
      .send('Temporarily unavailable, please retry.');
  }
});

// ── SSR Handler ────────────────────────────────────────────────
/*
 * Edge caching for rendered pages. Every page is public: SSR reads the API with X-SSR-Key only (no visitor
 * cookies or headers), and the theme preference is applied in the browser. Vercel's CDN keeps a page for
 * 5 minutes and then serves it stale while re-rendering in the background (for up to a day), so visitors
 * rarely wait for the function or the API (which cold-starts on Render's free tier). Admin edits appear
 * within ~5 minutes; a deploy purges the cache.
 * `Vercel-CDN-Cache-Control` is read by Vercel only: browsers and Cloudflare still revalidate every time.
 * Not cached: non-200 responses (404/503 pages, redirects) and pages that already set Cache-Control,
 * e.g. a render that fell back to defaults because the API was unreachable (site-initializer.ts).
 * Override with SSR_CDN_CACHE_CONTROL (empty string turns it off).
 */
const cdnCacheControl = process.env['SSR_CDN_CACHE_CONTROL'] ?? 'max-age=300, stale-while-revalidate=86400';

app.use((req, res, next) => {
  angularApp
    .handle(req)
    .then((response) => {
      if (!response) return next();
      if (
        cdnCacheControl &&
        (req.method === 'GET' || req.method === 'HEAD') &&
        response.status === 200 &&
        !response.headers.has('cache-control') &&
        response.headers.get('content-type')?.startsWith('text/html')
      ) {
        response.headers.set('Vercel-CDN-Cache-Control', cdnCacheControl);
      }
      return writeResponseToNodeResponse(response, res);
    })
    .catch(next);
});

// ── Start Server ───────────────────────────────────────────────
if (isMainModule(import.meta.url) || process.env['pm_id']) {
  const port = process.env['PORT'] || 4000;
  app.listen(port, (error) => {
    if (error) throw error;
    console.log(`Node Express server listening on http://localhost:${port}`);
  });
}

export const reqHandler = createNodeRequestHandler(app);
